
import express from 'express';
import cors from 'cors';
import path from 'path';
import { fileURLToPath } from 'url';
import { randomUUID } from 'node:crypto';
import { pool, verificarConexion } from './db.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = Number(process.env.PORT || 3001);

// ==========================================
// 1. CONFIGURACION DE SEGURIDAD
// ==========================================

// Ocultar informacion sobre Express
app.disable('x-powered-by');

// Cabeceras de seguridad
app.use((req, res, next) => {
  res.setHeader(
    'Strict-Transport-Security',
    'max-age=31536000; includeSubDomains'
  );

  res.setHeader('X-Content-Type-Options', 'nosniff');

  next();
});

app.use(cors());
app.use(express.json({ limit: '100kb' }));

// ==========================================
// 2. ARCHIVOS ESTATICOS DEL SITIO
// ==========================================

const distPath = path.join(__dirname, '../dist');

app.use(express.static(distPath));

// ==========================================
// 3. BASE DE DATOS POSTGRESQL
// ==========================================

// Crear la tabla si no existe.
// No se eliminan registros durante el inicio.
async function inicializarBaseDatos() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS reservaciones (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      codigo_reserva TEXT UNIQUE NOT NULL,
      parque_id TEXT,
      nombre_visitante TEXT NOT NULL,
      email_visitante TEXT NOT NULL,
      telefono_visitante TEXT,
      cantidad_visitantes INTEGER NOT NULL DEFAULT 1,
      fecha_visita TEXT NOT NULL,
      monto_total NUMERIC(12,2) DEFAULT 0.00,
      estado TEXT DEFAULT 'Pendiente',
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
  `);

  console.log('[DB] Tabla reservaciones verificada.');
}

// Codigo unico que no depende del reinicio del servidor
function generarCodigoReserva() {
  return `SINAC-${randomUUID()}`;
}

